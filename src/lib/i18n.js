const isValid = (c) => LANGUAGES.some((l) => l.code === c);

// Exposed so a test can assert the three dictionaries stay in step. A missing
// key silently falls back to English, which is how a translated UI ends up
// half-translated without anyone noticing.
export const dictionaryFor = (code) => DICT[isValid(code) ? code : "en"];

// `t(key)` returns the string; `t(key, params)` fills `{name}` placeholders.
// Substitution is deliberately simple — no pluralisation rules, because the
// three supported languages need only the count-aware wording the callers
// already pass in via their own {word} keys.
//
// This lives outside the hook so pure modules that format text (the date and
// deadline helpers, the dashboard radar lens) can localize without being a
// component. They read the language at call time, so any component that
// renders their output must subscribe with useI18n() to re-render on a switch.
const translateIn = (lang, key, params) => {
  const table = DICT[lang];
  const raw = table && table[key] !== undefined
    ? table[key]
    : (DICT.en[key] !== undefined ? DICT.en[key] : key);
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined || params[name] === null ? match : String(params[name]),
  );
};

export const translate = (key, params) => translateIn(getLang(), key, params);

// BCP-47 tags for Intl/toLocaleDateString. `en` maps to en-GB because the
// product's English copy is British ("organised" aside, dates read "18
// September" rather than "September 18").
const LOCALES = { en: "en-GB", ca: "ca-ES", es: "es-ES" };

export const localeFor = (code) => LOCALES[isValid(code) ? code : "en"];

// Module-level cache so getLang() mirrors document state across effect runs.
let current = null;

const readStored = () => {
  try {
    return localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
};

function detectLang() {
  const stored = typeof window !== "undefined" ? readStored() : null;
  if (stored && isValid(stored)) return stored;
  const nav = typeof navigator !== "undefined" ? (navigator.language || "").slice(0, 2).toLowerCase() : null;
  if (nav && isValid(nav)) return nav;
  return "en";
}

export const getLang = () => {
  if (current && isValid(current)) return current;
  current = detectLang();
  return current;
};

export const setLang = (code) => {
  if (!isValid(code)) return;
  current = code;
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    // storage unavailable — language still applies for this session
  }
  if (typeof document !== "undefined") document.documentElement.lang = code;
  if (typeof window !== "undefined") window.dispatchEvent(new CustomEvent(EVENT, { detail: code }));
};

export const useI18n = () => {
  const [lang, setLangState] = useState(getLang);

  useEffect(() => {
    if (typeof document !== "undefined" && isValid(document.documentElement.lang)) {
      document.documentElement.lang = lang;
    }
    const onLang = () => setLangState(getLang());
    window.addEventListener(EVENT, onLang);
    return () => window.removeEventListener(EVENT, onLang);
  }, [lang]);

  const t = (key, params) => translateIn(lang, key, params);

  return { lang, setLang, t, LANGUAGES };
};